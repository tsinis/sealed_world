import "dart:io";

import "package:path/path.dart";

import "l10n_package.dart";
import "templates/locale_fallback.dart";

export "l10n_package.dart";

/// Generates `lib/l10n_<name>.dart` of an l10n_* package from the files in its
/// `lib/src/data`, copies the shared sources from `lib/l10n/templates`, and
/// generates the tests that all l10n_* packages share, so that the mapper
/// logic and its tests have a single source for all l10n_* packages.
final class L10nMapperGenerator {
  /// Creates a generator for [package], with [root] as the `tools` directory.
  const new(this.package, {this.root = "."});

  /// The package to generate.
  final L10nPackage package;

  /// Path of the `tools` directory, all other paths are relative to it.
  final String root;

  static const _sharedSources = [
    "iso_locale_mapper.dart",
    "locale_fallback.dart",
  ];

  /// Test templates and the paths of the tests generated from them.
  static const _sharedTests = {
    "locale_resolution_test.tmpl": "test/locale_resolution_test.dart",
    "mapper_optimization_test.tmpl": "test/mapper_optimization_test.dart",
    "tree_shaking_test.tmpl": "integration_test/tree_shaking_test.dart",
  };
  static const _templatesPath = "lib/l10n/templates";
  static const _classTemplate = "locale_mapper.tmpl";
  static const _banner =
      "// GENERATED by `dart run :l10n_mapper` (tools/bin/l10n_mapper.dart)";
  static const _altNamesDoc = """
  /// The bundled translations include alternative (full) names, pass an empty
  /// string to look up only the common ones.""";
  static const _noAltNamesDoc = """
  /// The bundled translations ship no alternative names and are looked up
  /// without it, so it only applies to the translations injected via the
  /// `other` constructor parameter.""";

  /// A `{{name}}` placeholder of a template.
  static final _placeholder = RegExp(r"\{\{\w+\}\}");

  String get _packagePath =>
      normalize(join(root, "..", "packages", package.dirName));

  String get _libPath => join(_packagePath, "lib");

  List<_DataFile> get _dataFiles {
    final suffix = "_${package.name}_l10n.data.dart";
    final files =
        Directory(join(_libPath, "src", "data"))
            .listSync()
            .whereType<File>()
            .where((file) => file.path.endsWith(suffix))
            .toList()
          ..sort((a, b) => basename(a.path).compareTo(basename(b.path)));

    return List.unmodifiable(files.map(_DataFile.read));
  }

  /// Writes the generated files and returns their paths.
  List<String> run() {
    final files = _dataFiles;
    final library = File(join(_libPath, "${package.dirName}.dart"))
      ..writeAsStringSync(_library(files));
    final written = [library.path];

    for (final source in _sharedSources) {
      final target = File(join(_libPath, "src", source))
        ..writeAsStringSync(_fromTemplate(source));
      written.add(target.path);
    }

    final testValues = {
      "{{count}}": "${files.length}",
      "{{frenchName}}": package.frenchName,
      "{{germanName}}": package.germanName,
      "{{isoCode}}": package.isoCode,
      "{{mapper}}": package.mapperName,
      "{{package}}": package.dirName,
      "{{prefix}}": package.pascalName,
    };
    for (final MapEntry(key: source, value: test) in _sharedTests.entries) {
      final target = File(join(_packagePath, test))
        ..writeAsStringSync(_fromTemplate(source, values: testValues));
      written.add(target.path);
    }

    return written;
  }

  /// Returns the [source] template with the generated file banner, and with
  /// the placeholders of [values] filled in.
  String _fromTemplate(String source, {Map<String, String> values = const {}}) {
    final template = _readTemplate(source);

    return "$_banner from\n// tools/$_templatesPath/$source - DO NOT EDIT "
        "MANUALLY.\n\n${_fill(template, values)}";
  }

  String _readTemplate(String source) =>
      File(join(root, _templatesPath, source)).readAsStringSync();

  String _library(List<_DataFile> files) {
    final hasAltNames = files.any((file) => file.hasAltNames);
    // Directives keep the file name order, the rest uses the locale order.
    final byLocale = [...files]..sort(_compareLocales);
    final values = {
      "{{altDoc}}": hasAltNames ? _altNamesDoc : _noAltNamesDoc,
      "{{bundledLocales}}": byLocale
          .map((file) => '    "${file.locale}",')
          .join("\n"),
      "{{bundlesAltNames}}": "$hasAltNames",
      "{{count}}": "${files.length}",
      "{{example}}": package.exampleCodes,
      "{{factories}}": _factories(byLocale),
      "{{flags}}": byLocale.map((file) => _isOn(file.locale)).join(" ||\n"),
      "{{item}}": package.item,
      "{{mapper}}": package.mapperName,
      "{{package}}": package.dirName,
    };

    return _directives(files) + _fill(_readTemplate(_classTemplate), values);
  }

  /// Replaces every placeholder of [template] with its value in [values], in
  /// one pass, so a value is never searched for placeholders itself.
  static String _fill(String template, Map<String, String> values) => template
      .replaceAllMapped(_placeholder, (match) => _valueOf(match[0], values));

  static String _valueOf(String? placeholder, Map<String, String> values) =>
      values[placeholder] ??
      (throw StateError("No value for $placeholder in the template"));

  /// Orders the data files by locale, case-insensitively (`de` before `de_CH`
  /// and `zh` before `zh_Hant` in every package, unlike their file names).
  static int _compareLocales(_DataFile a, _DataFile b) =>
      a.locale.toLowerCase().compareTo(b.locale.toLowerCase());

  String _directives(List<_DataFile> files) {
    final buffer = StringBuffer()
      ..writeln("// This library translations are based on the data from the")
      ..writeln("// https://github.com/symfony/intl project")
      ..writeln(
        "// (from The Symfony - Intl Component, Fabien Potencier) and from the",
      )
      ..writeln(
        "// https://github.com/umpirsky/${package.item}-list project "
        // ignore: avoid-non-ascii-symbols, it's the name of the author.
        "(from Saša Stamenković).",
      )
      ..writeln("// Both projects are licensed under the MIT License.")
      ..writeln("//")
      ..writeln("$_banner from the")
      ..writeln("// files in src/data - DO NOT EDIT MANUALLY.")
      ..writeln()
      ..writeln(
        "// ignore_for_file: do_not_use_environment, "
        "avoid-collection-mutating-methods",
      )
      ..writeln(
        "// ignore_for_file: avoid-complex-conditions, avoid-collapsible-if",
      )
      ..writeln()
      ..writeln(
        "/// Provides ${package.item} translations for different locales.",
      )
      ..writeln("library ${package.dirName};")
      ..writeln()
      ..writeln('import "dart:collection" show UnmodifiableMapView;')
      ..writeln()
      ..writeAll(files.map((file) => 'import "src/data/${file.name}";\n'))
      ..writeln('import "src/iso_locale_mapper.dart";')
      ..writeln('import "src/locale_fallback.dart";')
      ..writeln()
      ..writeAll(files.map((file) => 'export "src/data/${file.name}";\n'))
      ..writeln('export "src/iso_locale_mapper.dart";')
      ..writeln();

    return buffer.toString();
  }

  /// Every entry is kept if its define says so (lowercase spelling first, then
  /// the locale spelling), otherwise if no opt-in define is set at all, or if
  /// a bundled child locale, which falls back to this one, is enabled.
  ///
  /// Only bundled locales get a define, so the rule is the same for every
  /// locale: `l10n-pt_BR` is ignored like `l10n-pt_AO` or the `l10n-fil`
  /// alias, even though [LocaleFallback.chain] resolves them at runtime.
  static String _factories(List<_DataFile> files) {
    // The parents of every locale, resolved once instead of once per pair.
    final parents = {
      for (final file in files)
        file.locale: LocaleFallback.chain(file.locale).skip(1).toSet(),
    };
    final buffer = StringBuffer();

    for (final file in files) {
      final key = file.locale;
      final lower = key.toLowerCase();
      final children = [
        for (final MapEntry(key: child, value: ofChild) in parents.entries)
          if (ofChild.contains(key)) child,
      ];
      final byDefault = [
        "!_hasAnyLocaleFilter",
        ...children.map(_isOn),
      ].join(" || ");
      final defaultValue = lower == key
          ? byDefault
          : 'bool.fromEnvironment("l10n-$key", defaultValue: $byDefault)';
      buffer
        ..writeln(
          '    if (const bool.fromEnvironment("l10n-$lower", '
          "defaultValue: $defaultValue))",
        )
        ..writeln('      "$key": ${file.className}.new,');
    }

    return buffer.toString().trimRight();
  }

  /// Whether `l10n-<locale>=true` is set, in lowercase or locale spelling.
  static String _isOn(String locale) => {
    locale.toLowerCase(),
    locale,
  }.map((name) => 'bool.fromEnvironment("l10n-$name")').join(" || ");
}

final class _DataFile {
  const new({
    required this.name,
    required this.className,
    required this.locale,
    required this.hasAltNames,
  });

  // ignore: avoid-non-empty-constructor-bodies, it parses the data file.
  factory read(File file) {
    final content = file.readAsStringSync();
    final className = _classRegExp.firstMatch(content)?.group(1);
    final locale = _localeRegExp.firstMatch(content)?.group(1);
    if (className == null || locale == null) {
      throw FormatException("No data class or locale in ${file.path}");
    }

    return _DataFile(
      name: basename(file.path),
      className: className,
      locale: locale,
      hasAltNames: _altNameRegExp.hasMatch(content),
    );
  }

  final String name;
  final String className;
  final String locale;
  final bool hasAltNames;

  static final _classRegExp = RegExp(
    r"^class (\w+) extends IsoLocaleMapper<String>",
    multiLine: true,
  );
  static final _localeRegExp = RegExp("translations for the `([^`]+)` locale");
  static final _altNameRegExp = RegExp(r'"[A-Za-z0-9]+\+":\s');
}
